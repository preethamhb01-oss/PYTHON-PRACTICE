def add(a, b, c=0, d=0, e=0, f=0):
    sum = a+b+c+d+e+f
    print(f"ANSWER FOR ADDITION OF {a, b, c, d, e, f} is --> {sum}")

    
def subtract(a, b, c=0, d=0, e=0, f=0):
    subtraction = a-b-c-d-e-f
    print(f"ANSWER FOR SUBTRACTION OF {a, b, c, d, e, f} is --> {subtraction}")
    
def multiply(a, b, c=1, d=1, e=1):
    multiply = a*b*c*d*e
    print(f"ANSWER FOR MULTIPLICATION OF {a, b, c, d, e} is --> {multiply}")